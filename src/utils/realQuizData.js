// Function to get quiz items based on gender
export const getQuizItemsByGender = (gender) => {
  console.log('getQuizItemsByGender called with gender:', gender);
  
  switch (gender) {
    case 'male':
      console.log('Returning male quiz items');
      return MALE_QUIZ_ITEMS;
    case 'female':
      console.log('Returning female quiz items');
      return FEMALE_QUIZ_ITEMS;
    case 'unisex':
    case 'non-binary':
    case 'prefer-not-to-say':
      console.log('Returning unisex quiz items');
      return UNISEX_QUIZ_ITEMS;
    default:
      console.log('No gender specified, returning unisex quiz items as default');
      return UNISEX_QUIZ_ITEMS;
  }
};

